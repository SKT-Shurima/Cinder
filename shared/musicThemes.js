/**
 * 固定主题配置的公开投影；检索词只供主进程构建真实平台候选。
 * 标识独立于显示名称，后续文案变化不影响入口、缓存和正在浏览的分类。
 */
export const musicThemes = Object.freeze(
  definitions.map(([id, name, group, description, keywords], index) =>
    Object.freeze({ id, name, group, description, keywords: Object.freeze(keywords), index, target: 100 }),
  ),
)

/**
 * 首页以华语歌曲为主要发现范围，跨语种及通用器乐主题仍可从完整主题页主动进入。
 * 这里只限定自动检索词，不凭歌名或歌手姓名猜测曲目语言，也不隐藏用户已有的歌曲。
 */
const homeThemes = musicThemes.filter(
  theme =>
    ![
      "western",
      "japanese",
      "korean",
      "jazz",
      "blues",
      "classical",
      "piano",
      "guitar",
      "strings",
      "instrumental",
      "game",
    ].includes(theme.id),
)

/**
 * 为首页换批生成轮换的华语检索范围及分页，供不同平台共用。
 * 粤语、闽南语与国乐保留自己的语种词，其余主题补充华语范围；结果仍由平台检索和播放权限核验决定。
 * 批次与轮次由调用方规范为非负整数；本函数不改变完整主题目录中的检索词和手动浏览顺序。
 */
export function homeRecommendationQuery(batch, round) {
  const cycle = Math.floor(batch / homeThemes.length)
  const theme = homeThemes[(batch + round * 7) % homeThemes.length]
  const word = theme.keywords[cycle % theme.keywords.length]
  return {
    keyword: ["chinese", "cantonese", "minnan", "chinese-instrument", "ancient"].includes(theme.id) ? word : `华语 ${word}`,
    playlistPage: (round % 4) + cycle * 12,
    songPage: 1 + (Math.floor(batch / (homeThemes.length * 3)) % 8),
  }
}
